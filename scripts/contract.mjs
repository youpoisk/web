import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { resolve, dirname } from 'node:path';
import openapiTS, { astToString } from 'openapi-typescript';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const contractPath = resolve(root, 'contracts/openapi.json');
const manifestPath = resolve(root, 'contracts/source.json');
const typesPath = resolve(root, 'src/shared/api/schema.d.ts');
const normalize = text => text.replace(/\r\n/g, '\n');
const digest = text => createHash('sha256').update(text).digest('hex');
const [mode, backend, ...extra] = process.argv.slice(2);
if (!['check', 'generate', 'import', 'check-source'].includes(mode) || extra.length ||
    (['import', 'check-source'].includes(mode) ? !backend : backend)) {
  throw new Error('Usage: node scripts/contract.mjs check|generate|import <backend-directory>|check-source <backend-directory>');
}
if (mode === 'import') {
  const cwd = resolve(backend);
  execFileSync('git', ['diff', '--quiet', 'HEAD', '--', 'api/openapi.json'], { cwd, stdio: 'pipe' });
  const commit = execFileSync('git', ['rev-parse', 'HEAD'], { cwd, encoding: 'utf8' }).trim();
  if (!/^[a-f0-9]{40}$/.test(commit)) throw new Error('Invalid backend commit');
  const raw = normalize(await readFile(resolve(cwd, 'api/openapi.json'), 'utf8'));
  JSON.parse(raw);
  await mkdir(dirname(contractPath), { recursive: true });
  await writeFile(contractPath, raw);
  await writeFile(manifestPath, JSON.stringify({ repository: 'youpoisk-backend', commit,
    path: 'api/openapi.json', sha256: digest(raw), generator: 'openapi-typescript@7.13.0' }, null, 2) + '\n');
}
const raw = normalize(await readFile(contractPath, 'utf8'));
const manifest = JSON.parse(await readFile(manifestPath, 'utf8'));
if (manifest.repository !== 'youpoisk-backend' || manifest.path !== 'api/openapi.json' ||
    !/^[a-f0-9]{40}$/.test(manifest.commit) || manifest.sha256 !== digest(raw) ||
    manifest.generator !== 'openapi-typescript@7.13.0') throw new Error('Contract provenance/hash mismatch; import the committed backend contract');
if (mode === 'check-source') {
  const source = normalize(await readFile(resolve(backend, 'api/openapi.json'), 'utf8'));
  if (digest(source) !== manifest.sha256) throw new Error('Backend contract changed; import and review the new contract');
}
const generated = '// Generated by scripts/contract.mjs; edit the backend contract instead.\n' +
  astToString(await openapiTS(JSON.parse(raw), { alphabetize: true }));
if (mode === 'check' || mode === 'check-source') {
  if (normalize(await readFile(typesPath, 'utf8')) !== generated) throw new Error('Generated API types drifted; run pnpm api:generate');
} else {
  await mkdir(dirname(typesPath), { recursive: true });
  await writeFile(typesPath, generated);
}
console.log('API contract and generated types verified.');
